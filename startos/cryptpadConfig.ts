import {
  UPSTREAM_HTTP_ADDRESS,
  UPSTREAM_HTTP_PORT,
  UPSTREAM_HTTP_SAFE_PORT,
  UPSTREAM_INSTALL_METHOD,
} from './utils'

/**
 * Generate config.js and infra.js — the two files CryptPad's server reads at
 * startup (lib/load-config.js@2026.10.0). We write both to the subcontainer
 * rootfs at /cryptpad/config/ on every restart; the upstream entrypoint's
 * `[ ! -f /cryptpad/config/config.js ]` and `[ ! -f /cryptpad/config/infra.js ]`
 * guards (docker-entrypoint.sh@2026.10.0) mean our pre-written files bypass
 * the entrypoint's copy-the-example branches entirely.
 *
 * Path overrides (filePath, blobPath, …) point at /data/* — the volume
 * mount. basePath holds sessions, MFA settings, invitations and registered
 * users, and logoPath the uploaded instance logo; upstream defaults both to
 * ./data/… under /cryptpad, which is ephemeral rootfs here.
 *
 * NOT overridden:
 *   - disableIntegratedEviction: upstream default (true, eviction disabled).
 *   - maxUploadSize, adminEmail, etc: managed via CryptPad's in-app
 *     /admin/ panel.
 */
export interface CryptpadConfigInputs {
  /** infra.public.origin — full origin (scheme://host[:port]) of the main UI. */
  origin: string
  /** infra.public.sandboxOrigin — full origin of the sandbox iframe. */
  sandboxOrigin: string
  /** Public signing keys mirrored into config.js's adminKeys array. */
  adminKeys: string[]
}

export function generateCryptpadConfig(inputs: CryptpadConfigInputs): string {
  const adminKeysJs =
    inputs.adminKeys.length === 0
      ? ''
      : '\n' +
        inputs.adminKeys.map((k) => `    ${JSON.stringify(k)}`).join(',\n') +
        '\n  '
  return `/* CryptPad config — auto-generated by StartOS on every restart. Do not edit;
 * any local changes are overwritten when the service restarts. Configuration
 * lives in StartOS actions and CryptPad's in-app /admin/ panel.
 */
module.exports = {
  installMethod: ${JSON.stringify(UPSTREAM_INSTALL_METHOD)},

  basePath:        '/data/base/',
  filePath:        '/data/datastore/',
  archivePath:     '/data/archive/',
  pinPath:         '/data/pins/',
  blockPath:       '/data/block/',
  blobPath:        '/data/blob/',
  blobStagingPath: '/data/blobstage/',
  taskPath:        '/data/tasks/',
  decreePath:      '/data/decrees/',
  logoPath:        '/data/logo/',
  logPath:         '/data/logs/',
  logToStdout:     true,

  adminKeys: [${adminKeysJs}],
}
`
}

export function generateCryptpadInfra(inputs: CryptpadConfigInputs): string {
  return `/* CryptPad infra — auto-generated by StartOS on every restart. Do not edit. */
module.exports = {
  public: {
    origin:        ${JSON.stringify(inputs.origin)},
    sandboxOrigin: ${JSON.stringify(inputs.sandboxOrigin)},
    httpHost:      ${JSON.stringify(UPSTREAM_HTTP_ADDRESS)},
    httpPort:      ${UPSTREAM_HTTP_PORT},
    httpSafePort:  ${UPSTREAM_HTTP_SAFE_PORT},
  },
  front: [
    { host: 'localhost', port: 3010 },
    { host: 'localhost', port: 3011 },
  ],
  core: [
    { host: 'localhost', port: 3020 },
    { host: 'localhost', port: 3021 },
  ],
  storage: [
    { host: 'localhost', port: 3030, wsPort: 3040 },
    { host: 'localhost', port: 3031, wsPort: 3041 },
  ],
}
`
}
